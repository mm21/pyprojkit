"""
Generation of the `pyprojkit-python` agent skill, in the
[Agent Skills](https://agentskills.io) format, from a project's configuration.

The skill tells agents about the project's workflow: when doit is enabled, each enabled
task (init, format, analysis, test) becomes a step to run before finishing a task, so
the skill always matches the tools actually configured.
"""

from __future__ import annotations

from .config.project import ProjectConfig

__all__ = [
    "render_skill",
]

SKILL_NAME = "pyprojkit-python"
"""
Name of the generated skill, and of its directory within each skill directory.
"""

_DESCRIPTION = (
    "Workflow and conventions for Python development in this project. Use when "
    "writing, modifying, or reviewing Python code."
)


def render_skill(config: ProjectConfig) -> str:
    """
    Render the contents of `SKILL.md` for the given project configuration.
    """
    sections = [
        _render_frontmatter(),
        "<!-- generated by pyprojkit (https://github.com/mm21/pyprojkit) from "
        "pyprojconf.py; do not edit -->",
        "# Python development",
        _render_project(config),
        _render_conventions(),
    ]

    if workflow := _render_workflow(config):
        sections.append(workflow)

    return "\n\n".join(sections) + "\n"


def _render_frontmatter() -> str:
    return "\n".join(
        [
            "---",
            f"name: {SKILL_NAME}",
            f"description: {_DESCRIPTION}",
            "---",
        ]
    )


def _render_project(config: ProjectConfig) -> str:
    requires = config.requires_python
    min_version = f"{requires.min[0]}.{requires.min[1]}"

    packages = config.resolved_packages
    if len(packages) == 1:
        package_lines = [
            f"- The package `{packages[0].name}` lives in `{packages[0].path.as_posix()}`."
        ]
    else:
        package_lines = ["- The project's packages live in:"] + [
            f"  - `{package.name}`: `{package.path.as_posix()}`" for package in packages
        ]

    lines = [
        "## Project",
        "",
        *package_lines,
        f"- Code must support Python {min_version}+ (`requires-python = "
        f'"{requires.specifier}"`): use modern syntax and standard library features '
        f"available in Python {min_version}, and don't add compatibility shims for "
        "older versions.",
    ]

    if (pinned := config.pinned_versions) is not None:
        versions = ", ".join(f"{maj}.{min}" for maj, min in pinned.versions)
        lines.append(f"- Tested Python versions: {versions}.")

    sync_cmd = _cmd(config, "doit sync" if config.tools.doit else "pyprojkit sync")
    lines.append(
        "- Tool configuration is declared in `pyprojconf.py` and synced into "
        "`pyproject.toml` by pyprojkit. Fields marked `# pyprojkit-managed` are "
        "overwritten on sync: to change them, edit `pyprojconf.py` and run "
        f"`{sync_cmd}` instead."
    )

    return "\n".join(lines)


def _render_workflow(config: ProjectConfig) -> str | None:
    tools = config.tools
    steps: list[str] = []

    # tasks can only be run through doit
    if tools.doit and tools.doc and tools.doc.mkinit:
        steps.append(
            f"`{_cmd(config, 'doit init')}`: regenerates `__init__.py` files using mkinit. Never edit "
            "the content between `# <AUTOGEN_INIT>` markers by hand; list submodules "
            "in `__submodules__` and declare each module's public symbols in its "
            "`__all__`."
        )

    if tools.doit and tools.formatting:
        steps.append(
            f"`{_cmd(config, 'doit format')}`: runs the configured formatters; don't hand-format code "
            "they will rewrite."
        )

    if (
        tools.doit
        and (analysis := tools.analysis)
        and (analysis.mypy or analysis.pyright)
    ):
        names = " and ".join(
            name
            for name, enabled in (
                ("mypy", analysis.mypy),
                ("pyright", analysis.pyright),
            )
            if enabled
        )
        steps.append(
            f"`{_cmd(config, 'doit analysis')}`: runs static analysis ({names}). Fix reported errors "
            "rather than suppressing them; use `# type: ignore` only as a last resort, "
            "with the specific error code."
        )

    if tools.doit and (test := tools.test):
        test_dirs = " or ".join(f"`{p}/`" for p in config.test_paths)
        test_dir = f" under {test_dirs}" if test_dirs else ""
        steps.append(
            f"`{_cmd(config, 'doit test')}`: runs the test suite with coverage. Add or update "
            f"tests{test_dir} for any changed behavior."
        )

    run_nox = bool(tools.nox and tools.test)
    if not steps and not run_nox:
        return None

    lines = ["## Before finishing a task", ""]

    if steps:
        lines += [
            "After changing Python code, run the following in order and resolve any "
            "failures before considering the task complete:",
            "",
        ]
        lines += [f"{i}. {step}" for i, step in enumerate(steps, 1)]

    if run_nox:
        if steps:
            lines.append("")
        lines.append(
            "For changes which may behave differently across Python versions, "
            f"{'also ' if steps else ''}run `{_cmd(config, 'nox')}` to test against every pinned version."
        )

    return "\n".join(lines)


def _render_conventions() -> str:
    return "\n".join(
        [
            "## Conventions",
            "",
            "- After completing an implementation, order definitions within each "
            "module so that internal (`_`-prefixed) symbols come after public symbols "
            "of the same kind: public constants before internal constants, public "
            "classes before internal classes, public functions before internal "
            "functions, and public methods before internal methods within a class. "
            "Python resolves names when code runs, not when it's defined, so helpers "
            "don't need to precede their callers.",
        ]
    )


def _cmd(config: ProjectConfig, command: str) -> str:
    """
    Get a command as it should be invoked, i.e. through the workflow tool if any.
    """
    if tool := config.tools.workflow_tool:
        return f"{tool} run {command}"
    return command
